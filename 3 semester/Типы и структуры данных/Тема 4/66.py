import sys


def solve():
    # Чтение всех данных сразу для ускорения
    data = sys.stdin.read().strip().split()
    if not data:
        print(0)
        return

    n = int(data[0])  # Количество грузов
    if n == 0:
        print(0)
        return

    events = []  # Список событий

    # Читаем все грузы и создаем события
    for i in range(n):
        t = int(data[2 * i + 1])  # Время начала
        l = int(data[2 * i + 2])  # Длительность
        # Событие начала: +1 в момент t (начало разгрузки)
        events.append((t, 1))
        # Событие окончания: -1 в момент t + l (конец разгрузки)
        events.append((t + l, -1))

    # Сортируем события:
    # 1. По времени (в порядке возрастания)
    # 2. При равенстве времени: сначала окончания (-1), потом начала (+1)
    #    Это гарантирует, что при окончании одного и начале другого события
    #    в один момент времени, мы сначала уменьшим счетчик, потом увеличим
    events.sort(key=lambda x: (x[0], x[1]))

    current = 0  # Текущее количество одновременно разгружаемых грузов
    max_count = 0  # Максимальное количество одновременно разгружаемых грузов

    # Проходим по всем событиям в хронологическом порядке
    for time, event_type in events:
        current += event_type  # Обновляем текущее количество
        if current > max_count:
            max_count = current  # Обновляем максимум

    print(max_count)


if __name__ == "__main__":
    solve()