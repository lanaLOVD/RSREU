def sift_down(a, i, n):
    """
    Просеивание элемента вниз в поддереве с корнем i.
    a - массив, i - текущий индекс, n - размер кучи.
    """
    while True:
        left = 2 * i + 1  # Индекс левого потомка
        right = 2 * i + 2  # Индекс правого потомка
        largest = i  # Предполагаем, что текущий элемент наибольший

        # Сравниваем с левым потомком
        if left < n and a[left] > a[largest]:
            largest = left
        # Сравниваем с правым потомком
        if right < n and a[right] > a[largest]:
            largest = right

        if largest == i:
            break  # Свойство кучи восстановлено

        # Меняем местами с наибольшим потомком
        a[i], a[largest] = a[largest], a[i]
        i = largest  # Переходим к позиции потомка


def heapsort(a):
    """Пирамидальная сортировка массива a."""
    n = len(a)

    # Построение кучи (heapify) - приведение массива к структуре кучи
    # Начинаем с последнего нелистового элемента (n//2 - 1)
    for i in range(n // 2 - 1, -1, -1):
        sift_down(a, i, n)

    # Извлечение элементов из кучи
    for end in range(n - 1, 0, -1):
        # Меняем корень (максимальный элемент) с последним элементом
        a[0], a[end] = a[end], a[0]
        # Восстанавливаем свойства кучи для уменьшенной кучи (размер end)
        sift_down(a, 0, end)


# Основная программа
n = int(input())  # Количество элементов
arr = list(map(int, input().split()))  # Чтение массива

heapsort(arr)  # Сортировка

print(*arr)  # Вывод отсортированного массива