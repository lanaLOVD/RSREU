#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n;  // Количество вершин в ориентированном графе
    cin >> n;  // Считываем количество вершин
    
    // Создаём матрицу смежности размером n×n
    // a[i][j] = 1 (или другое ненулевое значение), если есть ребро из i в j
    // a[i][j] = 0, если ребра из i в j нет
    vector<vector<int>> a(n, vector<int>(n));
    
    // Чтение матрицы смежности ориентированного графа
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            cin >> a[i][j];  // Считываем наличие/отсутствие ребра i→j
        }
    }
    
    // Векторы для хранения номеров истоков и стоков
    vector<int> sources;  // Истоки - вершины, в которые не входит ни одно ребро
    vector<int> sinks;    // Стоки - вершины, из которых не выходит ни одно ребро
    
    // Проверяем каждую вершину на то, является ли она истоком и/или стоком
    for (int i = 0; i < n; i++) {
        // Предполагаем, что вершина является истоком и стоком
        // Будем опровергать эти предположения при обнаружении рёбер
        bool is_source = true;  // Флаг: вершина - исток?
        bool is_sink = true;    // Флаг: вершина - сток?
        
        // Проверка на исток:
        // Вершина является истоком, если в неё НЕ ВХОДИТ ни одно ребро
        // В матрице смежности это означает, что ВСЕ элементы в СТОЛБЦЕ i равны 0
        // Проверяем все возможные рёбра, входящие в вершину i (j → i)
        for (int j = 0; j < n; j++) {
            if (a[j][i] != 0) { // Нашли ребро, входящее в i (из j в i)
                is_source = false;  // Значит, вершина не может быть истоком
                break;  // Дальнейшая проверка не нужна
            }
        }
        
        // Проверка на сток:
        // Вершина является стоком, если из неё НЕ ВЫХОДИТ ни одно ребро
        // В матрице смежности это означает, что ВСЕ элементы в СТРОКЕ i равны 0
        // Проверяем все возможные рёбра, исходящие из вершины i (i → j)
        for (int j = 0; j < n; j++) {
            if (a[i][j] != 0) { // Нашли ребро, исходящее из i (из i в j)
                is_sink = false;  // Значит, вершина не может быть стоком
                break;  // Дальнейшая проверка не нужна
            }
        }
        
        // Если вершина оказалась истоком, добавляем её в список истоков
        // Добавляем i+1, так как нумерация вершин в выводе должна быть с 1
        if (is_source) {
            sources.push_back(i + 1);
        }
        
        // Если вершина оказалась стоком, добавляем её в список стоков
        if (is_sink) {
            sinks.push_back(i + 1);
        }
    }
    
    // Вывод результатов в требуемом формате:
    
    // 1. Сначала выводим количество истоков
    cout << sources.size() << endl;
    // Затем выводим номера всех истоков (каждый с новой строки)
    for (int source : sources) {
        cout << source << endl;
    }
    
    // 2. Выводим количество стоков
    cout << sinks.size() << endl;
    // Затем выводим номера всех стоков (каждый с новой строки)
    for (int sink : sinks) {
        cout << sink << endl;
    }
    
    return 0;  // Успешное завершение программы
}
