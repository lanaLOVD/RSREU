#include <iostream>
#include <vector>
#include <set>
using namespace std;

int main()
{
    int n, m; // n - количество вершин, m - количество ребер в графе
    cin >> n >> m;
    
    // Используем set для хранения уникальных ребер
    // Пары (u, v) хранятся так, что u < v для устранения дублирования (u,v) и (v,u)
    set<pair<int, int>> edges;
    
    // Чтение рёбер графа
    for (int i = 0; i < m; i++)
    {
        int u, v; // Номера вершин, соединенных ребром
        cin >> u >> v;
        
        // Приводим ребро к каноническому виду: (min(u,v), max(u,v))
        // Это гарантирует, что ребро (1,2) и ребро (2,1) будут считаться одинаковыми
        if (u > v) swap(u, v);
        
        // Добавляем ребро в множество
        edges.insert({u, v});
    }
    
    // Вычисляем количество ребер в полном графе с n вершинами
    // В полном графе каждая пара вершин соединена ребром
    // Формула: C(n, 2) = n * (n - 1) / 2
    int required_edges = n * (n - 1) / 2;
    
    // Проверяем, является ли граф полным
    if (edges.size() == required_edges)
    {
        // Если количество уникальных ребер равно количеству ребер в полном графе,
        // значит каждая пара вершин соединена ребром
        cout << "YES" << endl;
    }
    else
    {
        // Если ребер меньше, значит некоторые пары вершин не соединены
        cout << "NO" << endl;
    }
    
    return 0;
}
