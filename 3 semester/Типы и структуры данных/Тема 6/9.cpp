#include <iostream>
#include <vector>
#include <queue>
#include <algorithm>
using namespace std;

// Возможные ходы коня (8 направлений)
// Конь ходит буквой "Г": на 2 клетки в одну сторону и на 1 в перпендикулярную
const int dx[] = {2, 2, 1, 1, -1, -1, -2, -2};
const int dy[] = {1, -1, 2, -2, 2, -2, 1, -1};

int main() {
    int n, x1, y1, x2, y2;
    cin >> n >> x1 >> y1 >> x2 >> y2;
    
    // Переводим в 0-индексацию для удобства работы с массивами
    // Пользователь вводит координаты от 1 до n
    x1--; y1--; x2--; y2--;
    
    // BFS для поиска кратчайшего пути коня
    // dist[x][y] - минимальное количество ходов от начальной позиции до (x,y)
    // -1 означает, что клетка еще не достигнута
    vector<vector<int>> dist(n, vector<int>(n, -1));
    
    // pred[x][y] - предыдущая клетка на пути к (x,y)
    // Используется для восстановления маршрута
    vector<vector<pair<int, int>>> pred(n, vector<pair<int, int>>(n, {-1, -1}));
    
    // Очередь для BFS (обхода в ширину)
    queue<pair<int, int>> q;
    
    // Начинаем с начальной позиции коня
    dist[x1][y1] = 0;
    q.push({x1, y1});
    
    // Основной цикл BFS
    while (!q.empty()) {
        // Берем текущую позицию из очереди
        auto [x, y] = q.front();
        q.pop();
        
        // Проверяем все возможные ходы коня из текущей позиции
        for (int i = 0; i < 8; i++) {
            int nx = x + dx[i];  // Новая координата x
            int ny = y + dy[i];  // Новая координата y
            
            // Проверяем, что новая позиция:
            // 1. Не выходит за границы доски (0 <= nx, ny < n)
            // 2. Еще не посещена (dist[nx][ny] == -1)
            if (nx >= 0 && nx < n && ny >= 0 && ny < n && dist[nx][ny] == -1) {
                // Обновляем расстояние до новой клетки
                dist[nx][ny] = dist[x][y] + 1;
                
                // Запоминаем, откуда мы пришли (для восстановления пути)
                pred[nx][ny] = {x, y};
                
                // Добавляем новую позицию в очередь для дальнейшего обхода
                q.push({nx, ny});
                
                // Оптимизация: если дошли до цели, можно прервать BFS
                // (но только если хотим найти только один кратчайший путь)
                if (nx == x2 && ny == y2) {
                    break;
                }
            }
        }
    }
    
    // Выводим минимальное количество ходов
    // BFS гарантирует, что dist[x2][y2] - кратчайшее расстояние
    cout << dist[x2][y2] << endl;
    
    // Восстанавливаем путь от конечной позиции к начальной
    vector<pair<int, int>> path;
    int x = x2, y = y2;
    
    // Идём от конца к началу по цепочке предков
    while (x != -1 && y != -1) {
        path.push_back({x, y});
        auto [px, py] = pred[x][y];
        x = px;
        y = py;
    }
    
    // Разворачиваем путь, так как мы собирали его от конца к началу
    reverse(path.begin(), path.end());
    
    // Выводим путь, переводя координаты обратно в 1-индексацию
    for (auto [x, y] : path) {
        cout << x + 1 << " " << y + 1 << endl;
    }
    
    return 0;
}
