#include <iostream>
#include <vector>
using namespace std;

// Глобальные переменные
vector<vector<int>> graph;  // Список смежности графа
vector<bool> visited;       // Массив посещенных вершин

// Функция обхода в глубину для проверки на наличие циклов
// v - текущая вершина
// parent - родительская вершина (откуда мы пришли)
void dfs(int v, int parent) {
    visited[v] = true;  // Помечаем вершину как посещенную
    
    // Обходим всех соседей вершины v
    for (int u : graph[v]) {
        // Пропускаем ребро обратно к родителю, так как это неориентированный граф
        if (u == parent) continue;
        
        // Если соседняя вершина уже посещена и это не родитель
        // Значит мы нашли цикл!
        if (visited[u]) {
            // Используем исключение для выхода из рекурсии при обнаружении цикла
            throw false; // Передаем false как признак наличия цикла
        }
        
        // Рекурсивно посещаем соседнюю вершину
        // Текущая вершина v становится родителем для u
        dfs(u, v);
    }
}

int main() {
    int n, m; // n - количество вершин, m - количество ребер
    cin >> n >> m;
    
    // Инициализация графа (индексация с 1)
    graph.resize(n + 1);
    visited.resize(n + 1, false);
    
    // Чтение ребер графа
    for (int i = 0; i < m; i++) {
        int a, b;
        cin >> a >> b;
        
        // Добавляем ребра в обе стороны (граф неориентированный)
        graph[a].push_back(b);
        graph[b].push_back(a);
    }
    
    // Используем блок try-catch для обработки обнаружения цикла
    try {
        // Запускаем DFS из вершины 1
        // -1 означает, что у вершины 1 нет родителя
        dfs(1, -1);
        
        // Проверяем, что все вершины были посещены
        // Если граф связный, DFS из одной вершины должен посетить все вершины
        for (int i = 1; i <= n; i++) {
            if (!visited[i]) {
                // Нашли непосещенную вершину - граф несвязный
                cout << "NO" << endl;
                return 0;
            }
        }
        
        // Проверяем количество ребер
        // В дереве должно быть ровно n-1 ребро
        if (m != n - 1) {
            cout << "NO" << endl;
            return 0;
        }
        
        // Все условия выполнены - это дерево
        cout << "YES" << endl;
        
    } catch (bool has_cycle) {
        // Поймали исключение - значит нашли цикл
        cout << "NO" << endl;
    }
    
    return 0;
}
