#include <iostream>
#include <vector>
using namespace std;

// Глобальные переменные
vector<vector<int>> graph;  // Список смежности графа
vector<int> color;          // Массив цветов вершин для DFS
bool cycle = false;         // Флаг наличия цикла

// Функция обхода в глубину с обнаружением циклов
// v - текущая вершина
void dfs(int v) {
    color[v] = 1;           // Помечаем вершину как "в процессе обработки" (серый)
    
    // Обходим всех соседей вершины v
    for (int w : graph[v]) {
        if (color[w] == 0) {    // Если вершина не посещалась (белая)
            dfs(w);             // Рекурсивно посещаем ее
        }
        else if (color[w] == 1) { // Если нашли вершину "в процессе обработки" (серую)
            cycle = true;       // Значит нашли цикл!
        }
    }
    
    color[v] = 2;           // Помечаем вершину как "полностью обработанную" (черную)
}

int main() {
    int n; // Количество вершин в графе
    cin >> n;
    
    // Инициализация структур данных
    graph.resize(n);        // Граф с n вершинами
    color.resize(n, 0);     // Изначально все вершины белые (не посещены)
    
    // Чтение матрицы смежности и преобразование в список смежности
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            int x;
            cin >> x;       // Читаем элемент матрицы
            
            // Если есть ребро из i в j (ориентированное)
            if (x == 1) {
                graph[i].push_back(j); // Добавляем j в список смежности вершины i
            }
        }
    }
    
    // Запуск DFS для всех непосещенных вершин
    for (int i = 0; i < n; i++) {
        if (color[i] == 0) {    // Если вершина еще не посещалась
            dfs(i);             // Запускаем DFS из нее
        }
        if (cycle) break;       // Если нашли цикл, можно прервать поиск
    }
    
    // Вывод результата: 1 если есть цикл, 0 если нет
    cout << (cycle ? 1 : 0) << endl;
    
    return 0;
}
