#include <iostream>
#include <vector>
using namespace std;

int main() {
    int n, m; // n - количество вершин, m - количество ребер
    cin >> n >> m;
    
    // Граф в виде списка смежности
    // graph[u] содержит все вершины v, куда идет ребро из u
    vector<vector<int>> graph(n + 1); // Индексация с 1 до n
    
    // Чтение ориентированного графа
    for (int i = 0; i < m; i++) {
        int u, v;
        cin >> u >> v;
        graph[u].push_back(v);
    }
    
    // Перестановка вершин (топологический порядок для проверки)
    // perm содержит номера вершин в некотором порядке
    vector<int> perm(n);
    for (int i = 0; i < n; i++) {
        cin >> perm[i];
    }
    
    // Создаем массив позиций вершин в перестановке
    // pos[vertex] = позиция (индекс) этой вершины в перестановке perm
    vector<int> pos(n + 1);
    for (int i = 0; i < n; i++) {
        pos[perm[i]] = i;
    }
    
    // Проверяем, является ли данная перестановка топологическим порядком
    // Для этого для каждого ребра u->v должно выполняться:
    // вершина u должна идти РАНЬШЕ вершины v в перестановке (pos[u] < pos[v])
    for (int u = 1; u <= n; u++) {
        // Проверяем все ребра, исходящие из вершины u
        for (int v : graph[u]) {
            // Если u идет ПОСЛЕ v в перестановке (pos[u] > pos[v])
            // Это нарушает топологический порядок
            if (pos[u] > pos[v]) {
                cout << "NO" << endl;
                return 0;
            }
        }
    }
    
    // Если все ребра удовлетворяют условию, перестановка является топологическим порядком
    cout << "YES" << endl;
    return 0;
}
