#include <iostream>
#include <vector>

using namespace std;

// Функция сортировки пузырьком в порядке невозрастания (убывания)
void BubbleSort(vector<int> A) {
    // Внешний цикл: проходим по всем элементам массива
    for (size_t i = 0; i + 1 != A.size(); ++i) {
        bool swapped = false;  // Флаг для оптимизации - проверяем, были ли обмены
        
        // Внутренний цикл: проходим по неотсортированной части массива
        // С каждым проходом самый "легкий" элемент всплывает в конец
        for (size_t j = 0; j + 1 + i != A.size(); ++j) {
            // Сравниваем соседние элементы
            if (A.at(j) < A.at(j + 1)) {
                // Если текущий элемент меньше следующего, меняем их местами
                swap(A.at(j), A.at(j + 1));
                swapped = true;  // Запоминаем, что был обмен
            }
        }
        
        // Оптимизация: если за проход не было ни одного обмена, массив отсортирован
        if (!swapped) {
            break;
        }
    }

    // Вывод отсортированного массива
    for (const int number : A) {
        cout << number << " ";
    }
}

int main() {
    int x;
    vector<int> numbers;
    
    // Чтение чисел из входного потока до конца ввода
    while (cin >> x) {
        numbers.push_back(x);
    }
    
    // Вызов функции сортировки пузырьком
    BubbleSort(numbers);
    
    return 0;
}
