#include <iostream>
#include <vector>

using namespace std;

// Функция для подсчета количества обменов при сортировке пузырьком
void CountSwaps(vector<int> A) {
    int count = 0;  // Счетчик количества обменов
    
    // Внешний цикл: проходим по всем элементам массива
    for (size_t i = 0; i + 1 != A.size(); ++i) {
        bool swapped = false;  // Флаг для проверки, были ли обмены в этом проходе
        
        // Внутренний цикл: проходим по неотсортированной части массива
        for (size_t j = 0; j + 1 + i != A.size(); ++j) {
            // Сравниваем соседние элементы (сортировка по возрастанию)
            if (A.at(j) > A.at(j + 1)) {
                // Если текущий элемент больше следующего, меняем их местами
                swap(A.at(j), A.at(j + 1));
                ++count;       // Увеличиваем счетчик обменов
                swapped = true;  // Отмечаем, что был обмен
            }
        }
        
        // Оптимизация: если за проход не было обменов, массив отсортирован
        if (!swapped) {
            break;
        }
    }

    // Вывод общего количества обменов
    cout << count;
}

int main() {
    int size;
    int x;
    vector<int> numbers;
    
    // Чтение размера массива
    cin >> size;
    
    // Чтение элементов массива
    for (int i = 0; i != size; ++i) {
        cin >> x;
        numbers.push_back(x);
    }
    
    // Вызов функции для подсчета обменов
    CountSwaps(numbers);
    
    return 0;
}
