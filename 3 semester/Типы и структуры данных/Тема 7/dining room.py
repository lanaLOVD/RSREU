def main():
    # Читаем количество вершин и рёбер
    n, m = map(int, input().split())

    # Инициализация матрицы расстояний
    INF = 10 ** 9  # "бесконечность" - очень большое число
    # Создаем матрицу n×n, заполненную INF
    dist = [[INF] * n for _ in range(n)]

    # Расстояние от вершины до самой себя = 0
    for i in range(n):
        dist[i][i] = 0

    # Чтение информации о рёбрах (дорогах)
    for _ in range(m):
        s, e, l = map(int, input().split())
        # Преобразуем из 1-индексации в 0-индексацию
        s -= 1
        e -= 1
        # Дороги двунаправленные (неориентированный граф)
        # Если между вершинами несколько дорог, берем самую короткую
        if l < dist[s][e]:
            dist[s][e] = l
            dist[e][s] = l  # так как граф неориентированный

    # ============================================================================
    # АЛГОРИТМ ФЛОЙДА-УОРШЕЛЛА
    # ============================================================================
    # Находит кратчайшие пути между всеми парами вершин
    for k in range(n):  # k - промежуточная вершина
        for i in range(n):  # i - начальная вершина
            # Оптимизация: если нет пути из i в k, пропускаем
            if dist[i][k] < INF:
                for j in range(n):  # j - конечная вершина
                    # Если есть путь из k в j и путь через k короче
                    if dist[k][j] < INF and dist[i][k] + dist[k][j] < dist[i][j]:
                        dist[i][j] = dist[i][k] + dist[k][j]

    # ============================================================================
    # ПОИСК "ЦЕНТРА" ГРАФА
    # ============================================================================
    # Ищем вершину с минимальным максимальным расстоянием до других вершин
    # Такая вершина называется "центром графа" или "медианой"

    min_max_dist = INF  # минимальное из максимальных расстояний
    best_vertex = 0  # номер лучшей вершины (в 0-индексации)

    for i in range(n):
        # Находим максимальное расстояние от вершины i до любой другой вершины
        max_dist = 0
        for j in range(n):
            if dist[i][j] > max_dist:
                max_dist = dist[i][j]

        # Если у этой вершины максимальное расстояние меньше текущего лучшего
        if max_dist < min_max_dist:
            min_max_dist = max_dist
            best_vertex = i  # запоминаем эту вершину как лучшую

    # Выводим номер вершины (возвращаем к 1-индексации)
    print(best_vertex + 1)


if __name__ == "__main__":
    main()