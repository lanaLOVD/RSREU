import sys
import heapq

# Используем быстрый ввод
input = sys.stdin.readline

# Читаем количество городов
N = int(input())

# Читаем цены на бензин в каждом городе
# price[i] - цена за литр бензина в городе i
price = list(map(int, input().split()))

# Читаем количество дорог между городами
M = int(input())

# Создаем список смежности для графа городов
# graph[u] будет содержать список городов, напрямую соединенных с городом u
graph = [[] for _ in range(N)]

# Читаем информацию о дорогах
for _ in range(M):
    u, v = map(int, input().split())
    # Преобразуем номера городов из 1-индексации в 0-индексацию
    u -= 1
    v -= 1
    # Добавляем дорогу в обе стороны (граф неориентированный)
    graph[u].append(v)
    graph[v].append(u)

# Инициализация расстояний (минимальной стоимости пути)
INF = 10 ** 9  # "бесконечность" - очень большое число
# dist[i] - минимальная стоимость добраться из города 0 в город i
dist = [INF] * N
dist[0] = 0  # в начальном городе стоимость пути 0

# Создаем кучу (min-heap) для реализации приоритетной очереди
# Храним пары (стоимость, город)
heap = [(0, 0)]  # начинаем с города 0 со стоимостью 0

# Основной цикл алгоритма Дейкстры
while heap:
    # Извлекаем город с минимальной текущей стоимостью
    cost, u = heapq.heappop(heap)

    # Проверяем, не устарела ли запись в куче
    # Если текущая стоимость больше минимальной известной для этого города,
    # значит, мы уже нашли более дешевый путь, игнорируем эту запись
    if cost > dist[u]:
        continue

    # Рассматриваем все города, напрямую соединенные с текущим городом u
    for v in graph[u]:
        # Новая стоимость = стоимость до города u + цена бензина в городе u
        # Предполагается, что чтобы проехать из u в v, нужно заправиться в u
        new_cost = cost + price[u]

        # Если найден более дешевый путь до города v
        if new_cost < dist[v]:
            # Обновляем минимальную стоимость
            dist[v] = new_cost
            # Добавляем новую запись в кучу
            heapq.heappush(heap, (new_cost, v))

# Выводим результат
# Если до последнего города (N-1) можно добраться, выводим минимальную стоимость,
# иначе выводим -1
print(dist[N - 1] if dist[N - 1] != INF else -1)