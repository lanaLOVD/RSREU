def dijkstra(graph, start, end):
    # n - количество вершин в графе
    n = len(graph)

    # visited - список посещенных вершин (True - посещена, False - не посещена)
    visited = [False] * n

    # dist - список минимальных расстояний от стартовой вершины до всех остальных
    # Изначально все расстояния бесконечны, кроме стартовой вершины (расстояние 0)
    dist = [float('inf')] * n
    dist[start] = 0

    # Основной цикл алгоритма Дейкстры
    # Выполняем n итераций (по одной для каждой вершины)
    for _ in range(n):
        # Ищем непосещенную вершину с минимальным расстоянием от старта
        min_dist = float('inf')
        min_index = -1  # индекс вершины с минимальным расстоянием

        # Проходим по всем вершинам
        for i in range(n):
            # Если вершина еще не посещена И ее текущее расстояние меньше найденного минимума
            if not visited[i] and dist[i] < min_dist:
                min_dist = dist[i]
                min_index = i

        # Если не нашли подходящую вершину (все достижимые вершины уже посещены)
        if min_index == -1:
            break

        # Помечаем найденную вершину как посещенную
        visited[min_index] = True

        # Обновляем расстояния до соседей текущей вершины
        for i in range(n):
            # graph[min_index][i] >= 0 означает, что существует ребро между вершинами
            # (в данной реализации 0 или положительное число - вес ребра, -1 - ребра нет)
            if graph[min_index][i] >= 0:
                # Пробуем дойти до вершины i через текущую вершину min_index
                new_dist = dist[min_index] + graph[min_index][i]
                # Если новый путь короче текущего лучшего пути до вершины i
                if new_dist < dist[i]:
                    dist[i] = new_dist  # обновляем минимальное расстояние

    # Возвращаем расстояние до конечной вершины
    # Если до нее нельзя добраться (расстояние осталось бесконечным), возвращаем -1
    return dist[end] if dist[end] != float('inf') else -1


# ====== ЧТЕНИЕ ВХОДНЫХ ДАННЫХ ======

# N - количество вершин в графе
# S - номер стартовой вершины (нумерация с 1 в входных данных)
# F - номер конечной вершины (нумерация с 1 в входных данных)
N, S, F = map(int, input().split())

# Преобразуем номера вершин в индексы массива (нумерация с 0)
S -= 1
F -= 1

# Читаем матрицу смежности графа
graph = []
for _ in range(N):
    # Каждая строка - список целых чисел, представляющих веса ребер
    # -1 означает отсутствие ребра, положительное число - вес ребра
    graph.append(list(map(int, input().split())))

# Вызываем алгоритм Дейкстры и выводим результат
print(dijkstra(graph, S, F))