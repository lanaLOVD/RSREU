# Читаем количество вершин, стартовую и конечную вершины
# Вершины нумеруются с 1 во входных данных
N, S, F = map(int, input().split())

# Преобразуем номера вершин в 0-индексацию для удобства работы с массивами
S -= 1
F -= 1

# Читаем матрицу смежности графа
graph = []
for _ in range(N):
    row = list(map(int, input().split()))
    # Заменяем -1 на float('inf') для обозначения отсутствия ребра
    # float('inf') - специальное значение "бесконечность" в Python
    graph.append([float('inf') if x == -1 else x for x in row])

# Инициализация массивов для алгоритма Дейкстры

# dist[i] - минимальное известное расстояние от S до вершины i
dist = [float('inf')] * N
dist[S] = 0  # расстояние от стартовой вершины до самой себя равно 0

# prev[i] - предыдущая вершина на кратчайшем пути от S до i
# Используется для восстановления пути
prev = [None] * N

# visited[i] - флаг, показывающий, была ли вершина i посещена
visited = [False] * N

# Основной цикл алгоритма Дейкстры
# Выполняем N итераций (по одной на каждую вершину)
for _ in range(N):
    # ШАГ 1: Выбираем непосещенную вершину с минимальным расстоянием
    u = -1  # индекс выбранной вершины
    min_dist = float('inf')  # минимальное расстояние

    # Перебираем все вершины
    for i in range(N):
        # Если вершина не посещена И её текущее расстояние меньше найденного минимума
        if not visited[i] and dist[i] < min_dist:
            min_dist = dist[i]
            u = i  # запоминаем индекс вершины с минимальным расстоянием

    # Если не нашли подходящую вершину (все достижимые вершины уже посещены)
    if u == -1:
        break  # выходим из цикла

    # Помечаем выбранную вершину как посещенную
    visited[u] = True

    # ШАГ 2: Обновляем расстояния до соседей выбранной вершины
    for v in range(N):
        # Проверяем, существует ли ребро из u в v (не равно бесконечности)
        if graph[u][v] != float('inf'):
            # Пробуем дойти до v через u
            new_dist = dist[u] + graph[u][v]

            # Если найден более короткий путь до v
            if dist[v] > new_dist:
                dist[v] = new_dist  # обновляем минимальное расстояние
                prev[v] = u  # запоминаем, что пришли в v из u

# Восстанавливаем путь от S до F
if dist[F] == float('inf'):
    # Если расстояние до конечной вершины осталось бесконечным,
    # значит, пути не существует
    print(-1)
else:
    # Создаем список для хранения пути
    path = []

    # Начинаем с конечной вершины
    cur = F

    # Идем по цепочке prev, пока не дойдем до None (стартовой вершины)
    while cur is not None:
        # Преобразуем обратно в 1-индексацию и добавляем в путь
        path.append(cur + 1)
        # Переходим к предыдущей вершине на пути
        cur = prev[cur]

    # Путь восстановлен в обратном порядке (от F к S),
    # поэтому разворачиваем его
    path.reverse()

    # Выводим путь: *path распаковывает список в аргументы print
    print(*path)