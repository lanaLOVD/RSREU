# Используем большое значение для "бесконечности"
# 10**18 достаточно для большинства задач, так как:
# - N ≤ 100 (судя по использованию O(N³) алгоритма)
# - Веса рёбер могут быть большими, но не настолько
INF = 10 ** 18

# Читаем количество вершин в графе
N = int(input())

# Инициализируем матрицу расстояний
dist = []
for _ in range(N):
    # Читаем строку матрицы смежности
    row = list(map(int, input().split()))
    # Добавляем копию строки в матрицу расстояний
    # [:] создает копию списка, чтобы не изменять оригинальные данные
    dist.append(row[:])  # комментарий говорит, что граф полный - все рёбра существуют

# ============================================================================
# АЛГОРИТМ ФЛОЙДА-УОРШЕЛЛА
# ============================================================================
# Находим кратчайшие пути между всеми парами вершин
for k in range(N):  # k - промежуточная вершина
    for i in range(N):  # i - начальная вершина
        for j in range(N):  # j - конечная вершина
            # Проверяем, можно ли улучшить путь из i в j,
            # пройдя через промежуточную вершину k
            if dist[i][k] + dist[k][j] < dist[i][j]:
                # Обновляем кратчайший путь
                dist[i][j] = dist[i][k] + dist[k][j]

# ============================================================================
# ПРОВЕРКА НА ОТРИЦАТЕЛЬНЫЕ ЦИКЛЫ
# ============================================================================
# В графе с отрицательными циклами понятие "кратчайший путь" не определено,
# так как можно бесконечно уменьшать длину пути, проходя по циклу.
# 
# После выполнения алгоритма Флойда-Уоршелла:
# - dist[i][i] должно быть равно 0 (расстояние от вершины до самой себя)
# - Если dist[i][i] < 0, значит существует отрицательный цикл, проходящий через вершину i
negative_cycle = any(dist[i][i] < 0 for i in range(N))

if negative_cycle:
    # Если обнаружен отрицательный цикл, выводим -1
    print(-1)
else:
    # ========================================================================
    # ПОИСК МИНИМАЛЬНОГО РАССТОЯНИЯ МЕЖДУ РАЗНЫМИ ВЕРШИНАМИ
    # ========================================================================
    # Инициализируем ответ очень большим значением
    ans = INF

    # Перебираем все пары различных вершин
    for i in range(N):
        for j in range(N):
            if i != j:  # пропускаем пары, где вершины совпадают
                # Обновляем минимальное найденное расстояние
                ans = min(ans, dist[i][j])

    # Выводим ответ
    print(ans)