# Читаем количество вершин в графе
N = int(input())

# Читаем матрицу смежности графа
# adj[i][j] = 1, если существует прямое ребро из i в j
# adj[i][j] = 0, если прямого ребра нет
adj = [list(map(int, input().split())) for _ in range(N)]

# ============================================================================
# АЛГОРИТМ ФЛОЙДА-УОРШЕЛЛА ДЛЯ ТРАНЗИТИВНОГО ЗАМЫКАНИЯ
# ============================================================================
# Этот алгоритм находит транзитивное замыкание графа.
# Транзитивное замыкание показывает, существует ли путь (не обязательно прямой)
# от вершины i к вершине j через любые промежуточные вершины.
# 
# Вместо суммы весов как в классическом Флойде-Уоршелле,
# здесь используется логическая операция И (AND).

for k in range(N):          # k - промежуточная вершина
    for i in range(N):      # i - начальная вершина
        for j in range(N):  # j - конечная вершина
            # Если существует путь из i в k И путь из k в j,
            # то существует и путь из i в j (через k)
            if adj[i][k] and adj[k][j]:
                adj[i][j] = 1  # отмечаем, что путь существует

# ============================================================================
# ВЫВОД РЕЗУЛЬТАТА
# ============================================================================
# Выводим матрицу транзитивного замыкания
# Теперь adj[i][j] = 1, если существует ЛЮБОЙ путь из i в j
# adj[i][j] = 0, если пути не существует
for row in adj:
    # *row распаковывает список, чтобы вывести числа через пробел
    print(*row)