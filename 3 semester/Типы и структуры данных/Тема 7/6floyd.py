# Константа для представления "бесконечности" (отсутствия пути)
INF = 10**9

# Читаем количество вершин (городов) и номера стартовой и конечной вершин
N, s, t = map(int, input().split())
# Преобразуем номера вершин из 1-индексации в 0-индексацию
s -= 1
t -= 1

# Инициализируем матрицу расстояний
dist = []
for _ in range(N):
    # Читаем строку матрицы смежности
    row = list(map(int, input().split()))
    dist_row = []
    for x in row:
        # Если в матрице указано -1, значит, прямого ребра нет
        # Заменяем -1 на INF (бесконечность)
        if x == -1:
            dist_row.append(INF)
        else:
            dist_row.append(x)
    # Добавляем обработанную строку в матрицу расстояний
    dist.append(dist_row)

# ============================================================================
# АЛГОРИТМ ФЛОЙДА-УОРШЕЛЛА
# ============================================================================
# Этот алгоритм находит кратчайшие пути между всеми парами вершин в графе.
# Основная идея: постепенно добавляем промежуточные вершины и проверяем,
# можно ли улучшить путь через них.
# Временная сложность: O(N³), где N - количество вершин.

# Внешний цикл: k - промежуточная вершина
# Мы проверяем, можно ли улучшить путь из i в j, пройдя через вершину k
for k in range(N):
    # Первый внутренний цикл: i - начальная вершина
    for i in range(N):
        # Второй внутренний цикл: j - конечная вершина
        for j in range(N):
            # Проверяем, короче ли путь из i в j через вершину k,
            # чем прямой путь или путь, найденный ранее
            # dist[i][k] - кратчайший путь из i в k
            # dist[k][j] - кратчайший путь из k в j
            if dist[i][k] + dist[k][j] < dist[i][j]:
                # Обновляем кратчайший путь из i в j
                dist[i][j] = dist[i][k] + dist[k][j]

# ============================================================================
# ВЫВОД РЕЗУЛЬТАТА
# ============================================================================
# Выводим кратчайшее расстояние от s до t
# Если пути не существует (расстояние равно INF), выводим -1
print(dist[s][t] if dist[s][t] != INF else -1)