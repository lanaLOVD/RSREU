import sys
import heapq

# Используем быстрый ввод
input = sys.stdin.readline

# Читаем количество городов
N = int(input())

# Читаем города отправления и назначения
# d - departure city (город отправления)
# v - destination city (город назначения)
d, v = map(int, input().split())
# Преобразуем из 1-индексации в 0-индексацию
d -= 1
v -= 1

# Читаем количество рейсов
R = int(input())

# Создаем список всех рейсов
# flights[i] содержит список рейсов, отправляющихся из города i
# Каждый рейс представлен как кортеж: (время отправления, город назначения, время прибытия)
flights = [[] for _ in range(N)]

# Читаем информацию о рейсах
for _ in range(R):
    # u - город отправления
    # t_dep - время отправления
    # w - город назначения
    # t_arr - время прибытия
    u, t_dep, w, t_arr = map(int, input().split())
    # Преобразуем номера городов в 0-индексацию
    flights[u - 1].append((t_dep, w - 1, t_arr))

# Инициализация массива минимального времени прибытия в каждый город
INF = 10 ** 9  # "бесконечность" - очень большое число
# arrival_time[i] - минимальное время прибытия в город i
arrival_time = [INF] * N
arrival_time[d] = 0  # в городе отправления мы находимся в момент времени 0

# Создаем кучу (min-heap) для реализации приоритетной очереди
# Храним пары (время прибытия, город)
heap = [(0, d)]  # начинаем с города d в момент времени 0

# Основной цикл алгоритма Дейкстры (модифицированного)
while heap:
    # Извлекаем город с минимальным временем прибытия
    cur_time, city = heapq.heappop(heap)

    # Проверяем, не устарела ли запись в куче
    # Если текущее время больше минимального известного для этого города,
    # значит, мы уже нашли более раннее прибытие, игнорируем эту запись
    if cur_time > arrival_time[city]:
        continue

    # Рассматриваем все рейсы, отправляющиеся из текущего города
    for t_dep, dest, t_arr in flights[city]:
        # Проверяем условие: мы можем успеть на рейс, только если
        # текущее время прибытия в город <= время отправления рейса
        if cur_time <= t_dep and arrival_time[dest] > t_arr:
            # Мы успеваем на этот рейс и прибываем в город назначения раньше,
            # чем любым другим известным способом
            arrival_time[dest] = t_arr  # обновляем минимальное время прибытия
            # Добавляем новую запись в кучу
            heapq.heappush(heap, (t_arr, dest))

# Выводим результат
# Если до города v можно добраться, выводим минимальное время прибытия,
# иначе выводим -1
print(arrival_time[v] if arrival_time[v] != INF else -1)