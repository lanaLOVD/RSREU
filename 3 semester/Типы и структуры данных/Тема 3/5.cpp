#include <iostream>
#include <vector>
#include <algorithm>
using namespace std;

// Функция проверки, можно ли разместить K коров в стойлах
// с минимальным расстоянием между ними не менее dist
// stalls - отсортированный массив координат стойл
// k - количество коров для размещения
// dist - минимальное расстояние между коровами
// Возвращает true, если можно разместить всех коров с таким расстоянием
bool canPlaceCows(const vector<int>& stalls, int k, int dist) {
    int count = 1; // Первую корову всегда ставим в первое стойло (самое левое)
    int last_position = stalls[0]; // Позиция последней размещенной коровы
    
    // Проходим по всем стойлам начиная со второго
    for (int i = 1; i < stalls.size(); i++) {
        // Если текущее стойло находится на расстоянии >= dist от последней коровы
        if (stalls[i] - last_position >= dist) {
            count++; // Размещаем корову в этом стойле
            last_position = stalls[i]; // Обновляем позицию последней коровы
            
            // Если разместили всех коров, можно досрочно выйти
            if (count >= k) {
                return true;
            }
        }
    }
    return false; // Не удалось разместить всех коров с заданным расстоянием
}

int main() {
    int N, K; // N - количество стойл, K - количество коров
    cin >> N >> K;
    
    vector<int> stalls(N);
    for (int i = 0; i < N; i++) {
        cin >> stalls[i]; // Читаем координаты стойл
    }
    
    // Сортируем стойла по координатам (обязательный шаг)
    sort(stalls.begin(), stalls.end());
    
    // Бинарный поиск по ответу (максимальному минимальному расстоянию)
    int left = 1; // Минимально возможное расстояние между коровами
    int right = stalls[N-1] - stalls[0]; // Максимально возможное расстояние
    int answer = 0; // Будем хранить здесь найденный ответ
    
    // Классический бинарный поиск
    while (left <= right) {
        int mid = left + (right - left) / 2; // Берем среднее расстояние
        
        if (canPlaceCows(stalls, K, mid)) {
            // Если можно разместить коров с расстоянием mid
            // Значит это допустимое расстояние, возможно есть и большее
            answer = mid; // Запоминаем текущий лучший результат
            left = mid + 1; // Пробуем большее расстояние
        } else {
            // Если нельзя разместить с расстоянием mid
            // Нужно уменьшить расстояние
            right = mid - 1; // Пробуем меньшее расстояние
        }
    }
    
    // Выводим максимальное минимальное расстояние
    cout << answer << endl;
    
    return 0;
}
