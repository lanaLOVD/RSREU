#include <iostream>
#include <vector>
#include <algorithm>
#include <cmath>

using namespace std;

int main() {
    int N, K; // N - количество веревок, K - сколько веревочек нужно получить
    cin >> N >> K;
    
    vector<int> ropes(N);
    long long totalLength = 0;  // Общая длина всех веревок
    int maxRope = 0;           // Длина самой длинной веревки
    
    // Чтение входных данных
    for (int i = 0; i < N; i++) {
        cin >> ropes[i];
        totalLength += ropes[i];        // Суммируем общую длину
        maxRope = max(maxRope, ropes[i]); // Находим самую длинную веревку
    }
    
    // Проверка тривиального случая: если общая длина меньше K,
    // то невозможно получить даже K веревочек длины 1
    if (totalLength < K) {
        cout << 0 << endl;
        return 0;
    }
    
    // Бинарный поиск максимальной длины веревочки
    int left = 1;          // Минимально возможная длина веревочки
    int right = maxRope;   // Максимально возможная длина (не может быть больше самой длинной веревки)
    int answer = 0;        // Здесь будем хранить найденный ответ
    
    // Классический бинарный поиск
    while (left <= right) {
        int mid = left + (right - left) / 2; // Пробуемая длина веревочки
        
        // Считаем, сколько веревочек длины mid можно получить из всех веревок
        long long count = 0;
        for (int i = 0; i < N; i++) {
            // Каждая веревка длины ropes[i] может дать ropes[i]/mid целых веревочек длины mid
            count += ropes[i] / mid;
        }
        
        if (count >= K) {
            // Если можем получить K или больше веревочек длины mid
            // Значит эта длина допустима, возможно есть и большее значение
            answer = mid;      // Запоминаем текущую найденную длину
            left = mid + 1;    // Пробуем большую длину
        } else {
            // Если не можем получить K веревочек длины mid
            // Нужно уменьшить длину
            right = mid - 1;   // Пробуем меньшую длину
        }
    }
    
    // Выводим максимальную длину веревочки, которую можно получить
    cout << answer << endl;
    
    return 0;
}
