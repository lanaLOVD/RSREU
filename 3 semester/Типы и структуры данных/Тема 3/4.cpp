#include <iostream>
#include <cmath>
#include <iomanip>

using namespace std;


double f(double a, double b, double c, double d, double x) {
    return a*x*x*x + b*x*x + c*x + d;
}

int main() {
    int a, b, c, d;
    cin >> a >> b >> c >> d;
    
    // Определяем интервал, содержащий корень
    double left, right;
    
    // Кубическое уравнение (степень 3) всегда имеет хотя бы один действительный корень
    // Находим интервал, где функция меняет знак
    
    // Начинаем с разумного интервала [-100, 100]
    // Это достаточно для коэффициентов, которые являются целыми числами
    left = -100.0;
    right = 100.0;
    
    // Уточняем интервал, содержащий корень
    // Если функция имеет одинаковый знак на концах интервала,
    // значит корень лежит за пределами этого интервала
    while (f(a, b, c, d, left) * f(a, b, c, d, right) > 0) {
        // Расширяем интервал в 2 раза
        left *= 2;
        right *= 2;
    }
    // После этого цикла: f(left) * f(right) ≤ 0
    // Значит на интервале [left, right] есть корень (по теореме Больцано-Коши)
    
    // Метод деления отрезка пополам (бисекции) для нахождения корня
    double precision = 1e-12;  // Требуемая точность
    while (right - left > precision) {
        double mid = (left + right) / 2;
        
        // Проверяем, в какой половине находится корень
        // Если f(left) и f(mid) имеют разные знаки,
        // то корень находится в левой половине [left, mid]
        if (f(a, b, c, d, left) * f(a, b, c, d, mid) <= 0) {
            right = mid;  // Сужаем интервал к левой половине
        } else {
            // Иначе корень в правой половине [mid, right]
            left = mid;   // Сужаем интервал к правой половине
        }
    }
    
    // Берем середину окончательного интервала как приближение корня
    double root = (left + right) / 2;
    
    // Выводим результат с высокой точностью
    cout << fixed << setprecision(15) << root << endl;
    
    return 0;
}
