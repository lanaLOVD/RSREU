#include <iostream>
#include <algorithm>
using namespace std;

int main() {
    long long w, h, n; // w - ширина диплома, h - высота диплома, n - количество дипломов
    cin >> w >> h >> n;
    
    // Бинарный поиск минимальной стороны квадратной доски
    long long left = 1; // Минимально возможная сторона доски
    long long right = max(w, h) * n; // Максимально возможная сторона доски
    // (если все дипломы выложить в один ряд/столбец)
    long long answer = right; // Инициализируем ответ максимальным значением
    
    while (left <= right) {
        long long mid = left + (right - left) / 2; // Пробуемая сторона доски
        
        // Считаем, сколько дипломов помещается по горизонтали и вертикали
        long long cols = mid / w; // Количество дипломов по ширине
        long long rows = mid / h; // Количество дипломов по высоте
        
        // Проверяем, помещаются ли все n дипломов на доску размера mid x mid
        // Условие: rows * cols >= n, но нужно аккуратно проверить переполнение
        
        if (cols > 0 && rows >= (n + cols - 1) / cols) {
            // cols > 0 - проверяем, что хотя бы один диплом помещается по ширине
            // (n + cols - 1) / cols - это округление вверх от n/cols
            // Если rows >= ceil(n/cols), значит все дипломы помещаются
            
            // Нашли допустимый размер доски, пробуем уменьшить
            answer = mid; // Запоминаем текущий лучший результат
            right = mid - 1; // Пробуем меньший размер доски
        } else {
            // Дипломы не помещаются, нужен больший размер доски
            left = mid + 1; // Пробуем больший размер доски
        }
    }
    
    // Выводим минимальную сторону квадратной доски
    cout << answer << endl;
    
    return 0;
}
