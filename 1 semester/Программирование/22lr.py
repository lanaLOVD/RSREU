from math import *

print("Введите исходные данные:")
x0 = float(input("x0 = "))  # Начальное значение x
hx = float(input("hx = "))  # Шаг изменения x
xn = float(input("xn = "))  # Конечное значение x

if x0 <= xn:
    print("Вы ввели:")
    print("x0 = %.2f \t hx = %.2f \t xn = %.2f" % (x0, hx, xn))
    print("    Табулирование функции:")

    x = x0
    while x < xn + hx / 2:
        p = 1  # Начальное значение произведения

        for k in range(0, 9):  # Внешнее произведение по k от 0 до 8 (включительно)
            for n in range(1, 6):  # Внутреннее произведение по n от 1 до 5 (включительно)
                term = k + sin(x) / n  # Текущий множитель
                p *= term  # Умножаем текущий множитель

        y = p  # Результат для данного x
        print("x = %.2f \t y = %.2f" % (x, y))  # Выводим результат
        x += hx  # Переходим к следующему значению x

else:
    print("Значения не удовлетворяют условию")