print ("Введите координаты точки М")
x = float(input("x = ")) #Первая координата для точки М
y = float(input("y = ")) #Вторая координата для точки м
r = 3 # Радиус окружности
y1 = (x ** 2 + y ** 2)**(1/2)
if (x <= 0 and y <= 0 and y1 <= r ) or (y <= x**2 + 2*x + 1 and 0 <= x <= 2.5 and y < x**2 + y**2) :
    print("Точка принадлежит области")
else:
    print("Точка не принадлежит области")