;;=================================================================
;;  ЗАДАНИЕ 11.5 — Дублирование образца 20 раз, вывод на экран
;;  Источник: Абель П., Глава 11, с. 116
;;
;;  Условие задачи:
;;    Определить поле с шест. значениями: 03h, 04h, 05h, B4h
;;    Продублировать его 20 раз и вывести результат на экран.
;;
;;  Метод (с. 112-113 Абеля):
;;    Образец (4 байта) помещается ПЕРЕД приёмной областью.
;;    После первой копии MOVSW автоматически дублирует образец,
;;    т.к. DI всегда опережает SI на длину образца.
;;    Итог: PATTERN (4б) + DISAREA (4*20=80б) = 84 байта вывода.
;;=================================================================

STACKSG SEGMENT PARA STACK 'Stack'
        DW      32 DUP(?)
STACKSG ENDS

;данные
;Сегмент данных: образец 4 байта + приёмная область 80 байт
DATASG  SEGMENT PARA 'Data'
        ;--- Образец: 4 байта шест. значений ---------------------
PATTERN DB      03H, 04H, 05H, 0B4H     ; Образец — 4 байта

        ;--- Приёмная область: 20 копий × 4 байта = 80 байт -----
DISAREA DB      80 DUP(0)          ; Область под 20 дублей образца

        ;--- Итоговая длина вывода: PATTERN + DISAREA = 84 байта -
OUT_LEN EQU     84                        ; Для функции вывода
DATASG  ENDS

;инициализация
;Инициализация сегментных регистров и точка входа
CODESG  SEGMENT PARA 'Code'
        ASSUME  CS:CODESG, DS:DATASG, SS:STACKSG, ES:DATASG

BEGIN   PROC    FAR                         ; Точка входа
        MOV     AX, DATASG
        MOV     DS, AX                       ; DS → сегмент данных
        MOV     ES, AX                       ; ES = DS (нужно для MOVS)

;дублирование
;Копирование образца в DISAREA и самовоспроизведение через MOVSW
        ;--- Шаг 1: скопировать PATTERN в начало DISAREA ----------
        ;    После этого: SI=PATTERN+4, DI=DISAREA+4
        ;    SI и DI разделены ровно на длину образца (4 байта).
        CLD                                  ; DF=0: слева направо
        LEA     SI, PATTERN                  ; SI → образец
        LEA     DI, DISAREA                  ; DI → начало приёмника
        MOV     CX, 2                          ; 2 слова = 4 байта
        REP     MOVSW                        ; Скопировать образец: DISAREA[0..3]

        ;--- Шаг 2: дублировать образец 19 раз -------------------
        ;    Теперь SI=PATTERN+4 (= DISAREA-0, т.к. PATTERN стоит
        ;    перед DISAREA в памяти), DI=DISAREA+4.
        ;    MOVSW берёт из DISAREA[0..] и пишет в DISAREA[4..],
        ;    тем самым автоматически тиражирует первые 4 байта.
        LEA     SI, DISAREA                  ; SI → начало уже скопированного образца
        ;    DI уже = DISAREA+4 после предыдущего REP MOVSW
        MOV     CX, 38                         ; 38 слов = 76 байт (19 копий × 4б)
        REP     MOVSW                        ; Дублировать: итого 20 копий в DISAREA
        
;вывод
;Вывод всех 84 байт (PATTERN + DISAREA) на экран через INT 21h
        ;--- Вывод результата на экран (INT 21h, функция 40h) ----
        ;    Выводим PATTERN + DISAREA = 84 байта подряд,
        ;    т.к. в памяти они расположены последовательно.
        MOV     AH, 40H                       ; Функция 40h: запись в файл/устройство
        MOV     BX, 1                          ; Дескриптор 1 = стандартный вывод (экран)
        MOV     CX, OUT_LEN                 ; CX = 84 байта
        LEA     DX, PATTERN                  ; DX → начало: с образца
        INT     21H                            ; Вывести 84 байта на экран

        ;--- Завершение программы --------------------------------
        MOV     AX, 4C00H
        INT     21H                            ; Выход в DOS

BEGIN   ENDP
CODESG  ENDS
        END     BEGIN